def ensure_csv():
    if not Path(ANNOTATIONS_CSV).exists():
        with open(ANNOTATIONS_CSV, "w", newline="", encoding="utf-8") as f:
            csv.DictWriter(f, fieldnames=CSV_FIELDNAMES).writeheader()

def append_row(record: dict):
    ensure_csv()
    with open(ANNOTATIONS_CSV, "a", newline="", encoding="utf-8") as f:
        csv.DictWriter(f, fieldnames=CSV_FIELDNAMES, extrasaction="ignore").writerow(record)



#  APP LOGIC

def _render(state):
    """Returns updated values for all UI components on each new pair."""
    pairs = state["pairs"]
    idx   = state["pair_idx"]
    done  = len(state["annotations"])
    total = len(pairs)

    if idx >= total:
        return (
            f"All done! {done}/{total} pairs annotated.",
            done / total,
            "", "", "", "",
            gr.update(visible=False),  # dim_block
            gr.update(visible=True),   # done_block
            gr.update(visible=True),   # annotation_block
        )

    pair = pairs[idx]
    return (
        f"Pair {done + 1} of {total}  ·  {state['annotator_id']}",
        done / total,
        f"**{pair['headline_a']}**",
        "",
        f"**{pair['headline_b']}**",
        "",
        gr.update(visible=False),
        gr.update(visible=False),
        gr.update(visible=True),
    )


def fn_start(name, state):
    name = name.strip()
    if not name:
        return state, *([gr.update()] * 9), "Please enter your name first."

    seed = hash(name) % 100_000
    state.update({
        "annotator_id": name,
        "pairs":        make_pairs(HEADLINES_DF, PAIRS_PER_SESSION, seed=seed),
        "pair_idx":     0,
        "annotations":  [],
        "winner":       None,
        "ratings":      {},
    })
    return state, *_render(state), gr.update(visible=False), ""


def fn_select(choice, state):
    state["winner"] = choice
    pair = state["pairs"][state["pair_idx"]]
    labels = {
        "A":   pair["headline_a"][:80] + "…",
        "B":   pair["headline_b"][:80] + "…",
        "tie": "(equal / can't decide)",
    }
    show_dims = choice != "tie"
    msg = f"Selected: **{labels[choice]}**"
    msg += "" if show_dims else " — click Submit to continue."
    return state, gr.update(visible=show_dims), msg


def fn_submit(state, *radio_vals):
    """radio_vals is one string per DIMENSION, e.g. ("3", "4") — or None if not picked."""
    if not state.get("winner"):
        return state, *([gr.update()] * 9), "Pick A, B, or Equal first."

    # Check all dimensions are rated (unless it's a tie)
    if state["winner"] != "tie":
        if any(v is None for v in radio_vals):
            return state, *([gr.update()] * 9), "Please rate all dimensions before submitting."

    for dim, val in zip(DIMENSIONS, radio_vals):
        state["ratings"][dim["id"]] = int(val) if val else None

    pair   = state["pairs"][state["pair_idx"]]
    record = {
        "annotator_id": state["annotator_id"],
        "pair_num":     len(state["annotations"]) + 1,
        "pair_key":     pair["pair_key"],
        "idx_a":        pair["idx_a"],
        "headline_a":   pair["headline_a"],
        "outlet_a":     pair["outlet_a"],
        "topic_a":      pair["topic_a"],
        "ideology_a":   pair["ideology_a"],
        "idx_b":        pair["idx_b"],
        "headline_b":   pair["headline_b"],
        "outlet_b":     pair["outlet_b"],
        "topic_b":      pair["topic_b"],
        "ideology_b":   pair["ideology_b"],
        "winner":       state["winner"],
        **{f"rating_{d['id']}": state["ratings"].get(d["id"]) for d in DIMENSIONS},
        "timestamp":    datetime.now().isoformat(),
    }

    append_row(record)
    state["annotations"].append(record)
    state["pair_idx"] += 1
    state["winner"]    = None
    state["ratings"]   = {}

    return state, *_render(state), f"Saved pair {record['pair_num']}."


def fn_skip(state):
    state["pair_idx"] += 1
    state["winner"]    = None
    state["ratings"]   = {}
    return state, *_render(state), "Skipped."



