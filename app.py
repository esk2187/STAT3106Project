#  DATA LOADING

def load_headlines():
    path = Path(CSV_PATH)
    if not path.exists():
        raise FileNotFoundError(
            f"CSV not found at:\n  {CSV_PATH}\n"
            "Check the path. On HF Spaces use just the filename."
        )

    df = pd.read_csv(path)
    print(f"Raw shape: {df.shape} | Columns: {list(df.columns)}")

    rename = {orig: internal for orig, internal in CSV_COLUMN_MAP.items()
              if orig in df.columns}
    df = df.rename(columns=rename)

    for orig in CSV_COLUMN_MAP:
        if orig not in rename:
            print(f"  Warning: '{orig}' not in CSV — skipping.")

    if "outlet"   not in df.columns: df["outlet"]   = "Unknown"
    if "topic"    not in df.columns: df["topic"]     = "unknown"
    if "ideology" not in df.columns: df["ideology"]  = "unknown"

    # Tags are comma-separated — keep first tag only for display
    def first_tag(val):
        if pd.isna(val) or str(val).strip() == "":
            return "unknown"
        return str(val).split(",")[0].strip()

    df["topic"] = df["topic"].apply(first_tag)

    df = df.dropna(subset=["headline"])
    df = df[df["headline"].str.strip() != ""].reset_index(drop=True)

    print(f"Loaded {len(df)} headlines.")
    print(df["ideology"].value_counts().to_string())
    return df


HEADLINES_DF = load_headlines()



#  PAIR GENERATION

def make_pairs(df, n, seed=None):
    """Randomly samples n unique pairs. Swaps A/B randomly to reduce position bias."""
    rng = random.Random(seed)
    indices = list(df.index)
    used, pairs = set(), []
    attempts = 0

    while len(pairs) < n and attempts < n * 30:
        attempts += 1
        i, j = rng.sample(indices, 2)
        key = (min(i, j), max(i, j))
        if key in used:
            continue
        used.add(key)
        if rng.random() > 0.5:
            i, j = j, i
        ra, rb = df.loc[i], df.loc[j]
        pairs.append({
            "pair_key":   f"{min(i,j)}-{max(i,j)}",
            "idx_a":      int(i),
            "headline_a": str(ra["headline"]),
            "outlet_a":   str(ra["outlet"]),
            "topic_a":    str(ra["topic"]),
            "ideology_a": str(ra["ideology"]),
            "idx_b":      int(j),
            "headline_b": str(rb["headline"]),
            "outlet_b":   str(rb["outlet"]),
            "topic_b":    str(rb["topic"]),
            "ideology_b": str(rb["ideology"]),
        })
    return pairs



